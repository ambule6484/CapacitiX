package com.capacitix.entity;

import jakarta.persistence.*;
import lombok.*;

import java.time.LocalDateTime;

@Entity
@Table(name = "assessments")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Assessment {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;


    /*
     * =========================================================
     * ASSESSMENT BASIC INFORMATION
     * =========================================================
     */

    @Column(nullable = false, length = 150)
    private String name;

    @Column(length = 1000)
    private String description;


    /*
     * =========================================================
     * ASSESSMENT TYPE
     * =========================================================
     *
     * Examples:
     * SKILL
     * TECHNICAL
     * PRACTICAL
     */

    @Column(nullable = false, length = 30)
    @Builder.Default
    private String type = "SKILL";


    /*
     * =========================================================
     * ASSESSMENT STATUS
     * =========================================================
     *
     * GENERATED  -> AI generated assessment
     * ASSIGNED   -> Trainer assigned it to employee
     * IN_PROGRESS -> Employee started assessment
     * COMPLETED  -> Employee completed assessment
     * PENDING    -> Waiting to be assigned
     */

    @Column(nullable = false, length = 30)
    @Builder.Default
    private String status = "GENERATED";


    /*
     * =========================================================
     * AI GENERATED
     * =========================================================
     *
     * TRUE  -> Assessment/questions generated by AI
     * FALSE -> Manually created if needed in future
     */

    @Column(name = "ai_generated", nullable = false)
    @Builder.Default
    private Boolean aiGenerated = true;


    /*
     * =========================================================
     * REQUIRED COMPETENCY / ROLE
     * =========================================================
     *
     * This stores the role for which the assessment was created.
     *
     * Example:
     * Java Backend Developer
     */

    @Column(name = "target_role", length = 150)
    private String targetRole;


    /*
     * =========================================================
     * QUESTION INFORMATION
     * =========================================================
     */

    @Column(name = "question_count", nullable = false)
    @Builder.Default
    private Integer questionCount = 0;


    /*
     * =========================================================
     * ASSIGNED EMPLOYEE
     * =========================================================
     *
     * IMPORTANT:
     *
     * AI generates the assessment first.
     * Therefore employee can be NULL initially.
     *
     * Trainer assigns the assessment later through
     * AssessmentAssignment.
     */

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "employee_id", nullable = true)
    private User employee;


    /*
     * =========================================================
     * ASSESSMENT SCORE
     * =========================================================
     */

    @Column(nullable = false)
    @Builder.Default
    private Integer score = 0;

    @Column(nullable = false)
    @Builder.Default
    private Integer maxScore = 100;


    /*
     * =========================================================
     * DATES
     * =========================================================
     */

    @Column(name = "created_at", nullable = false)
    @Builder.Default
    private LocalDateTime createdAt = LocalDateTime.now();

    @Column(name = "assigned_at")
    private LocalDateTime assignedAt;

    @Column(name = "started_at")
    private LocalDateTime startedAt;

    @Column(name = "completed_at")
    private LocalDateTime completedAt;


    /*
     * =========================================================
     * HELPER METHODS
     * =========================================================
     */

    public int getPercentage() {

        if (maxScore == null || maxScore <= 0) {
            return 0;
        }

        if (score == null || score <= 0) {
            return 0;
        }

        return (int) Math.round(
                ((double) score / maxScore) * 100
        );
    }


    public boolean isCompleted() {
        return "COMPLETED".equalsIgnoreCase(status);
    }


    public boolean isAssigned() {
        return "ASSIGNED".equalsIgnoreCase(status);
    }


    public boolean isInProgress() {
        return "IN_PROGRESS".equalsIgnoreCase(status);
    }


    public boolean isAiGenerated() {
        return Boolean.TRUE.equals(aiGenerated);
    }
}