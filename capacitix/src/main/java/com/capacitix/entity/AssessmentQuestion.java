package com.capacitix.entity;

import jakarta.persistence.*;
import lombok.*;

@Entity
@Table(name = "assessment_questions")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class AssessmentQuestion {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;


    /*
     * =========================================================
     * ASSESSMENT
     * =========================================================
     *
     * Every question belongs to one assessment.
     */

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "assessment_id", nullable = false)
    private Assessment assessment;


    /*
     * =========================================================
     * COMPETENCY / SKILL
     * =========================================================
     *
     * This is very important for skill-gap analysis.
     *
     * Example:
     *
     * Question:
     * "Which keyword is used to inherit a class in Java?"
     *
     * Competency:
     * Java OOP
     *
     * If employee answers incorrectly,
     * SkillAnalysisService can identify:
     *
     * Java OOP → Skill Gap
     */

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "competency_id", nullable = false)
    private Competency competency;


    /*
     * =========================================================
     * QUESTION
     * =========================================================
     */

    @Column(nullable = false, length = 2000)
    private String questionText;


    /*
     * =========================================================
     * QUESTION TYPE
     * =========================================================
     *
     * Currently mainly MCQ.
     *
     * Future:
     * TRUE_FALSE
     * SHORT_ANSWER
     * etc.
     */

    @Column(nullable = false, length = 30)
    @Builder.Default
    private String questionType = "MCQ";


    /*
     * =========================================================
     * OPTIONS
     * =========================================================
     *
     * For MCQ questions.
     */

    @Column(length = 1000)
    private String optionA;

    @Column(length = 1000)
    private String optionB;

    @Column(length = 1000)
    private String optionC;

    @Column(length = 1000)
    private String optionD;


    /*
     * =========================================================
     * CORRECT ANSWER
     * =========================================================
     *
     * Example:
     * A
     * B
     * C
     * D
     *
     * IMPORTANT:
     * The application will check the employee answer
     * against this value.
     *
     * AI is NOT used to decide whether the answer
     * is correct.
     */

    @Column(name = "correct_answer", nullable = false, length = 10)
    private String correctAnswer;


    /*
     * =========================================================
     * DIFFICULTY
     * =========================================================
     *
     * BEGINNER
     * INTERMEDIATE
     * ADVANCED
     */

    @Column(length = 30)
    @Builder.Default
    private String difficulty = "INTERMEDIATE";


    /*
     * =========================================================
     * MARKS
     * =========================================================
     */

    @Column(nullable = false)
    @Builder.Default
    private Integer marks = 1;


    /*
     * =========================================================
     * AI EXPLANATION
     * =========================================================
     *
     * Explanation generated by AI.
     *
     * It can be shown after the assessment
     * to help the employee understand the answer.
     */

    @Column(length = 2000)
    private String explanation;


    /*
     * =========================================================
     * QUESTION ORDER
     * =========================================================
     *
     * Example:
     * 1, 2, 3, 4...
     */

    @Column(name = "question_order", nullable = false)
    @Builder.Default
    private Integer questionOrder = 1;


    /*
     * =========================================================
     * ACTIVE
     * =========================================================
     */

    @Column(nullable = false)
    @Builder.Default
    private Boolean active = true;


    /*
     * =========================================================
     * HELPER METHOD
     * =========================================================
     */

    public boolean isCorrectAnswer(String answer) {

        if (answer == null || correctAnswer == null) {
            return false;
        }

        return correctAnswer.trim()
                .equalsIgnoreCase(answer.trim());
    }
}